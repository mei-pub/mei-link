export type DomainKind = "primary" | "custom" | "wildcard";

export type ManagedDomain = {
  domain: string;
  kind: DomainKind;
  enabled: boolean;
};

export type ServerConfig = {
  bindPort: number;
  vhostHTTPPort: number;
  vhostHTTPSPort: number;
  authToken: string;
  domains: ManagedDomain[];
  /**
   * frps 对外地址（客户端连接用的域名/IP，如 aicun.cc）。
   * 仅存 server.json 供客户端通过 /api/bootstrap 拉取，不写进 frps.toml（frps 不需要）。
   * 可选：留空时客户端无法用 bootstrap 自动填充，需手填。
   */
  serverAddr?: string;
};

const hostPattern = /^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;

function canonicalDomain(value: string) {
  return value.trim().toLowerCase().replace(/\.$/, "");
}

function assertDomain(domain: string, kind: DomainKind) {
  const wildcard = domain.startsWith("*.");
  const host = wildcard ? domain.slice(2) : domain;
  if (kind === "primary" && wildcard) throw new Error("主域名不能使用泛域名");
  if (kind === "wildcard" && !wildcard) throw new Error("泛域名必须以 *. 开头");
  if (kind !== "wildcard" && wildcard) throw new Error("泛域名必须使用泛域名类型");
  if (host.includes("*")) throw new Error("泛域名只能使用开头的 *. 通配符");
  if (!hostPattern.test(host)) throw new Error(`无效域名: ${domain}`);
}

export function normalizeDomains(input: ManagedDomain[]): ManagedDomain[] {
  const seen = new Set<string>();
  let primaryCount = 0;
  const domains = input.reduce<ManagedDomain[]>((domains, item) => {
    const domain = canonicalDomain(String(item.domain || ""));
    const kind = item.kind;
    const enabled = item.enabled !== false;
    assertDomain(domain, kind);
    if (kind === "primary" && enabled && ++primaryCount > 1) throw new Error("只能设置一个主域名");
    if (seen.has(domain)) return domains;
    seen.add(domain);
    domains.push({ domain, kind, enabled });
    return domains;
  }, []);
  const primary = domains.find((domain) => domain.kind === "primary" && domain.enabled)?.domain;
  if (primary && domains.some((domain) => domain.kind !== "primary" && domain.enabled && (domain.domain === primary || domain.domain.endsWith(`.${primary}`)))) {
    throw new Error("额外域名或泛域名不能属于主域名的子域名范围");
  }
  return domains;
}

function port(value: number, name: string) {
  if (!Number.isInteger(value) || value < 1 || value > 65535) throw new Error(`${name} 必须是 1-65535 的端口`);
  return value;
}

export function normalizeServerConfig(input: ServerConfig): ServerConfig {
  const authToken = String(input.authToken || "").trim();
  if (!authToken) throw new Error("FRP Token 不能为空");
  const serverAddr = String(input.serverAddr || "").trim();
  return {
    bindPort: port(Number(input.bindPort), "客户端连接端口"),
    vhostHTTPPort: port(Number(input.vhostHTTPPort), "HTTP 端口"),
    vhostHTTPSPort: port(Number(input.vhostHTTPSPort), "HTTPS 端口"),
    authToken,
    domains: normalizeDomains(Array.isArray(input.domains) ? input.domains : []),
    serverAddr: serverAddr || undefined,
  };
}

export function renderFrpsToml(config: ServerConfig): string {
  const normalized = normalizeServerConfig(config);
  const primary = normalized.domains.find((domain) => domain.kind === "primary" && domain.enabled);
  return [
    "# Generated by Meilink Server. Do not edit manually.",
    `bindPort = ${normalized.bindPort}`,
    `vhostHTTPPort = ${normalized.vhostHTTPPort}`,
    `vhostHTTPSPort = ${normalized.vhostHTTPSPort}`,
    ...(primary ? [`subDomainHost = ${JSON.stringify(primary.domain)}`] : []),
    "",
    'auth.method = "token"',
    `auth.token = ${JSON.stringify(normalized.authToken)}`,
    "",
    "# dashboard（仅容器内 127.0.0.1，不对外暴露；管理页代理端点用它拉取代理状态）",
    `webServer.addr = ${JSON.stringify(dashboardConfig().addr)}`,
    `webServer.port = ${dashboardConfig().port}`,
    `webServer.user = ${JSON.stringify(dashboardConfig().user)}`,
    `webServer.password = ${JSON.stringify(dashboardConfig().password)}`,
    "",
  ].join("\n");
}

/// frps 内置 dashboard 配置。固定绑 127.0.0.1（只本机访问，外部访问不到），
/// 端口默认 7500，凭据从环境变量读（默认 admin/admin，因仅本机访问风险低）。
/// 管理页的 /api/frps/* 代理端点用同一份凭据请求 dashboard API。
export type DashboardConfig = { addr: string; port: number; user: string; password: string };

export function dashboardConfig(env = process.env): DashboardConfig {
  return {
    addr: "127.0.0.1",
    port: Number(env.MEILINK_DASHBOARD_PORT || 7500),
    user: String(env.MEILINK_DASHBOARD_USER || "admin"),
    password: String(env.MEILINK_DASHBOARD_PASSWORD || "admin"),
  };
}

export function defaultServerConfig(env = process.env): ServerConfig {
  const primary = String(env.MEILINK_PRIMARY_DOMAIN || "").trim();
  const domains = primary ? [{ domain: primary, kind: "primary" as const, enabled: true }] : [];
  return {
    bindPort: Number(env.MEILINK_FRPS_BIND_PORT || 7000),
    vhostHTTPPort: Number(env.MEILINK_FRPS_HTTP_PORT || 8080),
    vhostHTTPSPort: Number(env.MEILINK_FRPS_HTTPS_PORT || 8443),
    authToken: String(env.MEILINK_FRPS_TOKEN || ""),
    domains,
  };
}
